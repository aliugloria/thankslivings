export const COUNTRIES: Country[] = ROWS.map(([code, name, extra]) => ({
  code,
  name,
  ...(typeof extra === "string" ? { atlas: extra } : extra ? { at: extra } : {}),
})).sort((a, b) => a.name.localeCompare(b.name, "en"));

const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

export function getCountry(code: string): Country | undefined {
  return BY_CODE.get(code.toUpperCase());
}

export function countryName(code: string): string {
  return getCountry(code)?.name ?? code;
}

export function isKnownCountry(code: string): boolean {
  return BY_CODE.has(code.toUpperCase());
}

/** Regional-indicator flag emoji, e.g. "NG" -> 🇳🇬 */
export function flagEmoji(code: string): string {
  const c = code.toUpperCase();
  if (!/^[A-Z]{2}$/.test(c)) return "🌍";
  return String.fromCodePoint(
    ...[...c].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65),
  );
}
